"""Score urgency on the val rows that have an urgency label (P3.3).

    python -m triage.eval_urgency        # == make urgency-eval

Always scores the heuristic; also scores the fine-tuned model when
models/urgency/ is valid. Writes results/urgency/{metrics.json, report.md}.
The heuristic was written from general support-desk vocabulary before this
run and is not tuned on val; test is never read here.
"""

from __future__ import annotations

import argparse
import json
import logging
import time
from pathlib import Path

import pandas as pd

from app.settings import REPO_ROOT
from data.build import OUT_DIR
from eval.classification import urgency_metrics
from eval.runinfo import run_info
from triage.urgency import UrgencyModel, UrgencyPredictor, heuristic_urgency

logger = logging.getLogger(__name__)

RESULTS = REPO_ROOT / "results" / "urgency"


def _summary(gold: pd.Series, pred: list[str], seconds: float) -> dict:
    m = urgency_metrics(list(gold), pred)
    m["predicted_counts"] = pd.Series(pred).value_counts().to_dict()
    m["ms_per_ticket"] = round(seconds * 1000 / max(len(pred), 1), 3)
    return m


def evaluate(
    out: Path = RESULTS, data_dir: Path = OUT_DIR, model: UrgencyModel | None = None
) -> dict:
    val = pd.read_parquet(data_dir / "val.parquet")
    val = val[val["urgency"].notna()]
    texts = list(val["text"])
    m: dict = {"rows": len(val), "gold_counts": val["urgency"].value_counts().to_dict()}

    t0 = time.perf_counter()
    heur = [heuristic_urgency(t) for t in texts]
    m["heuristic"] = _summary(val["urgency"], [h.urgency for h in heur], time.perf_counter() - t0)
    fired = pd.Series([s for h in heur for s in h.signals]).value_counts().to_dict()
    m["heuristic"]["signal_counts"] = fired

    model = model if model is not None else UrgencyModel()
    if model.available:
        t0 = time.perf_counter()
        res = UrgencyPredictor(model).predict(texts)
        m["model"] = _summary(val["urgency"], [r.urgency for r in res], time.perf_counter() - t0)
        m["model"]["version"] = model.version
        m["model"]["critical_overrides"] = sum(r.source == "heuristic" for r in res)
    else:
        reason = model.reason.replace(f"{REPO_ROOT}/", "")  # no local paths in results
        m["model"] = {"status": f"unavailable: {reason}"}
    m["run"] = run_info(split="val")
    out.mkdir(parents=True, exist_ok=True)
    (out / "metrics.json").write_text(json.dumps(m, indent=2, default=str))
    (out / "report.md").write_text(report_markdown(m))
    return m


def report_markdown(m: dict) -> str:
    lines = [
        "# Urgency on val (rows with an urgency label)",
        "",
        f"n={m['rows']}; gold {m['gold_counts']}. Generated by `make urgency-eval`.",
        "Ordinal MAE is over positions low=0, medium=1, high=2, critical=3.",
        "",
        "| source | macro-F1 | accuracy | ordinal MAE | off by >= 2 | predicted |",
        "|---|---|---|---|---|---|",
    ]
    for name in ("heuristic", "model"):
        s = m[name]
        if "macro_f1" in s:
            lines.append(
                f"| {name} | {s['macro_f1']} | {s['accuracy']} | {s['ordinal_mae']} | "
                f"{s['off_by_two_or_more']} | {s['predicted_counts']} |"
            )
        else:
            lines.append(f"| {name} | {s['status']} | | | | |")
    lines += ["", f"Heuristic signal counts: {m['heuristic']['signal_counts']}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(RESULTS))
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    m = evaluate(Path(args.out))
    print(report_markdown(m))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
