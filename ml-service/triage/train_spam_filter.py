"""Train the binary spam filter (P3.9) and choose its operating point.

    python -m triage.train_spam_filter        # == make spam-filter

1. C from SPAM_C_GRID by val average precision (PR-AUC), fitted on spam_train.
2. Thresholds on spam_val (support tickets = Tobi-Bueck + synthetic meetings;
   ham is reported separately):
   - spam (mute): the lowest threshold with support-ticket FPR <= MAX_FPR_MUTE (1%);
   - review: the lowest threshold with support-ticket FPR <= MAX_FPR_REVIEW (5%).
3. Report recall, FPR (support, ham) and review-band shares on spam_val (the
   selection set) and spam_test (held out). Saves models/spam_filter/ and
   results/spam_filter/{metrics.json, report.md}.
"""

from __future__ import annotations

import argparse
import json
import logging
import time
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

from app.settings import REPO_ROOT, get_settings
from data.build import OUT_DIR
from eval.runinfo import run_info
from triage.fast_tier import CARD_FILE, MODEL_FILE
from triage.spam_filter import HAM, REVIEW, SPAM, SpamFilter, build_filter, decide

logger = logging.getLogger(__name__)

RESULTS = REPO_ROOT / "results" / "spam_filter"
SPAM_C_GRID = (1.0, 4.0, 16.0)
MAX_FPR_MUTE = 0.01
MAX_FPR_REVIEW = 0.05
HAM_SOURCE = "spamassassin_ham"


def threshold_for_fpr(neg_scores, max_fpr: float) -> float:
    """Lowest threshold t with mean(neg_scores >= t) <= max_fpr."""
    s = np.sort(np.asarray(neg_scores, dtype=float))[::-1]
    k = int(np.floor(max_fpr * len(s)))  # false positives allowed
    if k >= len(s):
        return 0.0
    return float(min(1.0, np.nextafter(s[k], np.inf)))


def groups(df: pd.DataFrame) -> dict[str, np.ndarray]:
    is_ham = (df["source_dataset"] == HAM_SOURCE).to_numpy()
    spam = df["is_spam"].to_numpy(dtype=bool)
    return {"spam": spam, "support": ~spam & ~is_ham, "ham": ~spam & is_ham}


def operating_point(df: pd.DataFrame, scores, spam_t: float, review_t: float) -> dict:
    dec = np.array([decide(s, spam_t, review_t) for s in scores])
    out = {}
    for name, mask in groups(df).items():
        d = dec[mask]
        out[name] = {
            "n": int(mask.sum()),
            "muted_as_spam": round(float((d == SPAM).mean()), 4) if len(d) else None,
            "review_band": round(float((d == REVIEW).mean()), 4) if len(d) else None,
            "passed": round(float((d == HAM).mean()), 4) if len(d) else None,
        }
    out["recall_at_mute"] = out["spam"]["muted_as_spam"]
    out["recall_at_review"] = round(out["spam"]["muted_as_spam"] + out["spam"]["review_band"], 4)
    out["fpr_support_at_mute"] = out["support"]["muted_as_spam"]
    out["fpr_ham_at_mute"] = out["ham"]["muted_as_spam"]
    return out


def ranking_metrics(y, scores) -> dict:
    from sklearn.metrics import average_precision_score, roc_auc_score

    return {
        "average_precision": round(float(average_precision_score(y, scores)), 4),
        "roc_auc": round(float(roc_auc_score(y, scores)), 4),
    }


def report_markdown(m: dict) -> str:
    c = m["card"]
    lines = [
        "# Spam filter (binary, TF-IDF + LR)",
        "",
        f"Version `{c['version']}`. Generated by `make spam-filter`. Positives: SpamAssassin spam; "
        "negatives: SpamAssassin ham + support tickets (Tobi-Bueck + synthetic meetings).",
        f"Thresholds chosen on spam_val: **mute ≥ {c['spam_threshold']:.4f}** (support FPR ≤ "
        f"{MAX_FPR_MUTE:.0%}), **review ≥ {c['review_threshold']:.4f}** (support FPR ≤ "
        f"{MAX_FPR_REVIEW:.0%}). C={c['C']} by val average precision.",
        "",
        "| split | spam recall (mute) | spam recall (mute+review) | support FPR (mute) | "
        "support in review | ham FPR (mute) | ham in review | AP | ROC-AUC |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for split in ("val", "test"):
        o, r = m[split]["operating_point"], m[split]["ranking"]
        lines.append(
            f"| {split} | {o['recall_at_mute']} | {o['recall_at_review']} | "
            f"{o['fpr_support_at_mute']} (n={o['support']['n']}) | {o['support']['review_band']} | "
            f"{o['fpr_ham_at_mute']} (n={o['ham']['n']}) | {o['ham']['review_band']} | "
            f"{r['average_precision']} | {r['roc_auc']} |"
        )
    lines += [
        "",
        "val is the selection set for C and both thresholds; test is held out.",
        "",
        "### Alternative rule `support_and_ham`: same FPR limits on support tickets **and** ham",
        "",
        "**The default since P3.12** (chosen on val + ood-dev: it meets the support-FPR limit "
        "and mutes no reviewed human-written ood-dev email); `SPAM_RULE=support` selects the "
        "rule above.",
        "",
        f"mute ≥ {m['alternative_support_and_ham']['spam_threshold']:.4f}, review ≥ "
        f"{m['alternative_support_and_ham']['review_threshold']:.4f}",
        "",
        "| split | spam recall (mute) | spam recall (mute+review) | support FPR (mute) | "
        "ham FPR (mute) | ham in review |",
        "|---|---|---|---|---|---|",
        *[
            f"| {s} | {o['recall_at_mute']} | {o['recall_at_review']} | "
            f"{o['fpr_support_at_mute']} | {o['fpr_ham_at_mute']} | {o['ham']['review_band']} |"
            for s, o in ((s, m["alternative_support_and_ham"][s]) for s in ("val", "test"))
        ],
        "",
        "| C | val AP | fit s |",
        "|---|---|---|",
        *[f"| {r['C']} | {r['val_average_precision']} | {r['fit_s']} |" for r in m["c_selection"]],
        "",
        f"Peak RSS {m['run']['peak_rss_mb']} MB; swap at end: {m['run']['swap_usage_at_end']}.",
        "",
    ]
    return "\n".join(lines)


def train(
    model_dir: Path | None = None,
    out: Path = RESULTS,
    data_dir: Path = OUT_DIR,
    grid=SPAM_C_GRID,
) -> dict:
    import joblib
    import sklearn

    model_dir = Path(model_dir or get_settings().models_dir / "spam_filter")
    tr = pd.read_parquet(data_dir / "spam_train.parquet")
    val = pd.read_parquet(data_dir / "spam_val.parquet")
    test = pd.read_parquet(data_dir / "spam_test.parquet")
    manifest = json.loads((data_dir / "manifest.json").read_text())

    rows, best = [], None
    for c in grid:
        t0 = time.perf_counter()
        model = build_filter(c).fit(tr["text"], tr["is_spam"])
        pos = list(model.classes_).index(True)
        ap = ranking_metrics(val["is_spam"], model.predict_proba(val["text"])[:, pos])
        row = {"C": c, "val_average_precision": ap["average_precision"],
               "fit_s": round(time.perf_counter() - t0, 1)}  # fmt: skip
        logger.info("C=%s val AP %.4f", c, row["val_average_precision"])
        rows.append(row)
        if best is None or row["val_average_precision"] > best[0]["val_average_precision"]:
            best = (row, model)
    best_row, model = best

    trained_at = datetime.now(UTC)
    train_sha = manifest["splits"]["spam_train"]["content_sha256"]
    card = {
        "version": f"spam-{trained_at:%Y%m%d%H%M%S}-{train_sha[:8]}",
        "task": "spam",
        "model": "tfidf(word 1-2 + char_wb 3-5) + LR (balanced), binary is_spam",
        "trained_at": trained_at.isoformat(timespec="seconds"),
        "trained_on": {
            "spam_train_content_sha256": manifest["splits"]["spam_train"]["content_sha256"]
        },
        "C": best_row["C"],
        "sklearn_version": sklearn.__version__,
    }
    filt = SpamFilter(model, {**card, "spam_threshold": 1.0, "review_threshold": 1.0})
    val_scores = filt.scores(list(val["text"]))
    support = groups(val)["support"]
    card["spam_threshold"] = threshold_for_fpr(val_scores[support], MAX_FPR_MUTE)
    card["review_threshold"] = min(
        card["spam_threshold"], threshold_for_fpr(val_scores[support], MAX_FPR_REVIEW)
    )
    card["threshold_rule"] = (
        f"lowest scores with support-ticket FPR <= {MAX_FPR_MUTE} (mute) and "
        f"<= {MAX_FPR_REVIEW} (review) on spam_val"
    )
    test_scores = filt.scores(list(test["text"]))
    m: dict = {"card": card, "c_selection": rows}
    for name, df, sc in (("val", val, val_scores), ("test", test, test_scores)):
        m[name] = {
            "operating_point": operating_point(
                df, sc, card["spam_threshold"], card["review_threshold"]
            ),
            "ranking": ranking_metrics(df["is_spam"], sc),
            "score_quantiles_by_group": {
                g: [round(float(q), 4) for q in np.quantile(sc[mask], [0.5, 0.9, 0.99])]
                for g, mask in groups(df).items()
            },
        }
    # Alternative rule (stored, selectable with SPAM_RULE): the same FPR limits
    # applied to support tickets AND ham (human-written legitimate mail).
    ham = groups(val)["ham"]
    alt_spam = max(card["spam_threshold"], threshold_for_fpr(val_scores[ham], MAX_FPR_MUTE))
    alt_review = min(
        alt_spam,
        max(card["review_threshold"], threshold_for_fpr(val_scores[ham], MAX_FPR_REVIEW)),
    )
    m["alternative_support_and_ham"] = {
        "spam_threshold": alt_spam,
        "review_threshold": alt_review,
        **{
            name: operating_point(df, sc, alt_spam, alt_review)
            for name, df, sc in (("val", val, val_scores), ("test", test, test_scores))
        },
    }
    card["default_rule"] = "support_and_ham"  # chosen on val + ood-dev (P3.12)
    card["rules"] = {
        "support": {
            "spam_threshold": card["spam_threshold"],
            "review_threshold": card["review_threshold"],
            "description": card["threshold_rule"],
        },
        "support_and_ham": {
            "spam_threshold": alt_spam,
            "review_threshold": alt_review,
            "description": f"as 'support', and also ham FPR <= {MAX_FPR_MUTE} (mute) and "
            f"<= {MAX_FPR_REVIEW} (review) on spam_val",
        },
    }
    card["val_metrics"] = {
        "recall_at_mute": m["val"]["operating_point"]["recall_at_mute"],
        "fpr_support_at_mute": m["val"]["operating_point"]["fpr_support_at_mute"],
        "average_precision": m["val"]["ranking"]["average_precision"],
    }
    m["run"] = run_info(split="spam_val+spam_test")

    model_dir.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, model_dir / MODEL_FILE, compress=3)
    (model_dir / CARD_FILE).write_text(json.dumps(card, indent=2))
    if SpamFilter.load(model_dir) is None:
        raise RuntimeError(f"saved spam filter in {model_dir} failed to load")
    out.mkdir(parents=True, exist_ok=True)
    (out / "metrics.json").write_text(json.dumps(m, indent=2, default=str))
    (out / "report.md").write_text(report_markdown(m))
    return m


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--model-dir", default=None)
    ap.add_argument("--out", default=str(RESULTS))
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    m = train(args.model_dir, Path(args.out))
    print(report_markdown(m))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
