"""Train the fast tier (P3.1) on `train`, select C and report on `val`.

    python -m triage.train_fast_tier          # == make fast-tier

1. For each C in the grid, fit the uncalibrated pipeline on train and score
   val macro-F1 (the selection rule; cheap, no calibration folds).
2. Refit the best C uncalibrated and with each calibration method (sigmoid,
   isotonic; CalibratedClassifierCV, 5-fold on train); keep the one with the
   best val macro-F1 (ties: lower ECE). On the 5-class rebuild the CV
   calibrators learn train's class priors and cost ~12 macro-F1 points, so
   "none" can win (P3.12).
3. Report the calibrated model on val: reporting-rule slices, confusion
   matrix, calibration (ECE + reliability plot), the confidence/coverage
   table P3.4 uses to pick tau, latency, RSS and swap.
4. Save models/fast_tier/{model.joblib, model_card.json} and
   results/fast_tier/{metrics.json, confusion_matrix.png, reliability.png, report.md}.

The test split is never read here (it is reported once, in P7.1).
"""

from __future__ import annotations

import argparse
import json
import logging
import time
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

from app.settings import REPO_ROOT, get_settings
from app.taxonomy import topic_categories
from data.build import OUT_DIR
from eval.classification import (
    calibration,
    classification_metrics,
    confusion,
    coverage_curve,
    latency_summary,
    plot_confusion,
    plot_reliability,
    sliced_metrics,
)
from eval.runinfo import run_info
from triage.fast_tier import CALIBRATION_FOLDS, CARD_FILE, MODEL_FILE, FastTier, build_calibrated
from triage.fast_tier import build_pipeline as _pipeline

logger = logging.getLogger(__name__)

RESULTS = REPO_ROOT / "results" / "fast_tier"
C_GRID = (1.0, 4.0, 16.0, 64.0)
CALIBRATION_METHODS = ("none", "sigmoid", "isotonic")
TAUS = (0.4, 0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.95)
SEED = 42


def select_c(train: pd.DataFrame, val: pd.DataFrame, grid=C_GRID) -> tuple[float, list[dict]]:
    """Best C by uncalibrated val macro-F1 (ties: the smaller C)."""
    rows = []
    for c in grid:
        t0 = time.perf_counter()
        pipe = _pipeline(c).fit(train["text"], train["category"])
        pred = pipe.predict(val["text"])
        m = classification_metrics(val["category"], pred, topic_categories())
        rows.append(
            {
                "C": c,
                "val_macro_f1": m["macro_f1"],
                "val_accuracy": m["accuracy"],
                "fit_s": round(time.perf_counter() - t0, 1),
            }
        )
        logger.info("C=%s val macro-F1 %.4f acc %.4f", c, m["macro_f1"], m["accuracy"])
    best = max(rows, key=lambda r: (r["val_macro_f1"], -r["C"]))
    return best["C"], rows


def _latency(model: FastTier, texts: list[str], n: int) -> dict:
    rng = np.random.default_rng(SEED)
    sample = [texts[i] for i in rng.choice(len(texts), size=min(n, len(texts)), replace=False)]
    single = []
    for t in sample:
        t0 = time.perf_counter()
        model.predict([t])
        single.append((time.perf_counter() - t0) * 1000)
    t0 = time.perf_counter()
    model.predict(texts)
    batch_s = time.perf_counter() - t0
    return {
        "single_ticket_ms": latency_summary(single),
        "batch_all_val": {
            "tickets": len(texts),
            "wall_s": round(batch_s, 2),
            "ms_per_ticket": round(batch_s * 1000 / len(texts), 3),
        },
    }


def report_markdown(m: dict) -> str:
    v = m["val"]["overall"]
    lines = [
        "# Fast tier (TF-IDF + LR, calibrated) on val",
        "",
        f"Version `{m['card']['version']}`, trained on train"
        + (
            f" + train_style_aug ({m['card']['style_aug_rows']} rows)"
            if m["card"]["style_aug"]
            else ""
        )
        + f" ({m['card']['train_rows']} rows, "
        f"content `{m['card']['trained_on']['train_content_sha256'][:12]}`). "
        "Generated by `make fast-tier`. The test split is not used here.",
        "",
        f"- **Val macro-F1 {v['macro_f1']}**, accuracy {v['accuracy']} (n={v['n']})",
    ]
    for key, label in (
        ("origin_real", "real only"),
        ("without_meeting_scheduling", "without Meeting"),
    ):
        s = m["val"][key]
        lines.append(f"- {label}: macro-F1 {s['macro_f1']}, accuracy {s['accuracy']} (n={s['n']})")
    mm = m["val"]["real_meeting_mentions"]
    lines += [
        f"- real tickets mentioning a meeting word: n={mm['n']}, accuracy {mm['accuracy']}, "
        f"{mm['predicted_meeting']} predicted Meeting",
        f"- calibration ({m['card']['calibration']['method']}): ECE {m['calibration']['ece']} "
        f"(uncalibrated LR: "
        f"{m['calibration_uncalibrated_lr']['ece']})",
        "",
        "## C selection (uncalibrated, val macro-F1)",
        "",
        "| C | macro-F1 | accuracy | fit s |",
        "|---|---|---|---|",
        *[
            f"| {r['C']} | {r['val_macro_f1']} | {r['val_accuracy']} | {r['fit_s']} |"
            for r in m["c_selection"]
        ],
        "",
        "## Calibration method (C fixed, val)",
        "",
        "| method | ECE | macro-F1 | fit s |",
        "|---|---|---|---|",
        *[
            f"| {r['method']} | {r['val_ece']} | {r['val_macro_f1']} | {r['fit_s']} |"
            for r in m["calibration_selection"]
        ],
        "",
        f"Selected: **{m['card']['calibration']['method']}**.",
        "",
        "## Per class (calibrated, val)",
        "",
        "| class | precision | recall | F1 | support |",
        "|---|---|---|---|---|",
        *[
            f"| {c} | {p['precision']} | {p['recall']} | {p['f1']} | {p['support']} |"
            for c, p in v["per_class"].items()
        ],
        "",
        "## Confidence vs coverage (input for P3.4's tau)",
        "",
        "| tau | share with confidence >= tau | accuracy of that share |",
        "|---|---|---|",
        *[
            f"| {r['tau']} | {r['accepted_share']} | {r['accepted_accuracy']} |"
            for r in m["coverage"]
        ],
        "",
        "## Cost",
        "",
        f"- training (C search + calibrated fit): {m['training']['total_s']} s; "
        f"artifact {m['training']['artifact_mb']} MB",
        f"- load {m['latency']['load_s']} s; single ticket p50 "
        f"{m['latency']['single_ticket_ms']['p50_ms']} ms, p95 "
        f"{m['latency']['single_ticket_ms']['p95_ms']} ms; batch "
        f"{m['latency']['batch_all_val']['ms_per_ticket']} ms/ticket",
        f"- peak RSS {m['run']['peak_rss_mb']} MB; swap at end: {m['run']['swap_usage_at_end']}",
        "",
    ]
    return "\n".join(lines)


def train(
    model_dir: Path | None = None,
    out: Path = RESULTS,
    data_dir: Path = OUT_DIR,
    grid=C_GRID,
    folds: int = CALIBRATION_FOLDS,
    latency_n: int = 100,
    methods=CALIBRATION_METHODS,
    style_aug: bool = False,
) -> dict:
    import joblib
    import sklearn

    model_dir = Path(model_dir or get_settings().models_dir / "fast_tier")
    train_df = pd.read_parquet(data_dir / "train.parquet")
    aug_rows = 0
    if style_aug:  # ablation: train + train_style_aug; selection stays on val
        aug = pd.read_parquet(data_dir / "train_style_aug.parquet")
        aug_rows = len(aug)
        train_df = pd.concat([train_df, aug.drop(columns=["aug_of"])], ignore_index=True)
    val = pd.read_parquet(data_dir / "val.parquet")
    manifest = json.loads((data_dir / "manifest.json").read_text())
    t_start = time.perf_counter()

    best_c, c_rows = select_c(train_df, val, grid)
    candidates = []
    for method in methods:
        logger.info("C=%s: fitting %s calibration (%d folds)", best_c, method, folds)
        t0 = time.perf_counter()
        model = _pipeline(best_c) if method == "none" else build_calibrated(best_c, folds, method)
        cal = model.fit(train_df["text"], train_df["category"])
        fit_s = time.perf_counter() - t0
        probs = cal.predict_proba(val["text"])
        pred = cal.classes_[probs.argmax(axis=1)]
        ok = pred == val["category"].to_numpy()
        row = {
            "method": method,
            "val_ece": calibration(probs.max(axis=1), ok)["ece"],
            "val_macro_f1": classification_metrics(val["category"], pred, topic_categories())[
                "macro_f1"
            ],
            "fit_s": round(fit_s, 1),
        }
        logger.info("%s: val ECE %.4f macro-F1 %.4f", method, row["val_ece"], row["val_macro_f1"])
        candidates.append((row, cal))
    cal_rows = [r for r, _ in candidates]
    # Same rule as every model here: val macro-F1 first; ECE breaks ties.
    best_row, clf = min(candidates, key=lambda rc: (-rc[0]["val_macro_f1"], rc[0]["val_ece"]))
    method, fit_s = best_row["method"], best_row["fit_s"]
    total_s = time.perf_counter() - t_start

    trained_at = datetime.now(UTC)
    train_sha = manifest["splits"]["train"]["content_sha256"]
    card = {
        "version": f"fast-{trained_at:%Y%m%d%H%M%S}-{train_sha[:8]}",
        "task": "category",
        "model": f"tfidf(word 1-2 + char_wb 3-5) + LR (balanced), {method}-calibrated",
        "trained_at": trained_at.isoformat(timespec="seconds"),
        "trained_on": {
            "export_tag": manifest["splits"]["test"]["content_sha256"][:12],
            "train_content_sha256": manifest["splits"]["train"]["content_sha256"],
        },
        "train_rows": len(train_df),
        "style_aug": style_aug,
        "style_aug_rows": aug_rows,
        "C": best_c,
        "calibration": {"method": method, "folds": folds, "ensemble": False},
        "sklearn_version": sklearn.__version__,
        "classes": [str(c) for c in clf.classes_],
    }

    model_dir.mkdir(parents=True, exist_ok=True)
    joblib.dump(clf, model_dir / MODEL_FILE, compress=3)
    # Val metrics are added to the card below, after scoring the saved artifact.
    (model_dir / CARD_FILE).write_text(json.dumps(card, indent=2))

    t0 = time.perf_counter()
    model = FastTier.load(model_dir)
    load_s = time.perf_counter() - t0
    if model is None:
        raise RuntimeError(f"saved fast tier in {model_dir} failed to load")
    preds = model.predict(list(val["text"]))
    res = val[["id", "origin", "category", "text"]].rename(columns={"category": "gold"})
    res["pred"] = [p.category for p in preds]
    res["confidence"] = [p.confidence for p in preds]
    correct = (res["gold"] == res["pred"]).to_numpy()

    # Calibration of the plain LR (the selected C, fitted inside the calibrated
    # model's estimator) for comparison.
    base = (
        clf.calibrated_classifiers_[0].estimator if hasattr(clf, "calibrated_classifiers_") else clf
    )
    raw = base.predict_proba(val["text"])
    raw_classes = list(base.classes_)
    raw_pred = [raw_classes[i] for i in raw.argmax(axis=1)]
    raw_correct = np.asarray(raw_pred) == res["gold"].to_numpy()

    labels = topic_categories()
    cm = confusion(res["gold"], res["pred"], labels)
    m: dict = {
        "card": card,
        "val": sliced_metrics(res, labels=topic_categories()),
        "confusion_matrix": {"labels": labels, "matrix": cm},
        "calibration": calibration(res["confidence"], correct),
        "calibration_uncalibrated_lr": calibration(raw.max(axis=1), raw_correct),
        "coverage": coverage_curve(res["confidence"], correct, TAUS),
        "c_selection": c_rows,
        "calibration_selection": cal_rows,
        "training": {
            "total_s": round(total_s, 1),
            "calibrated_fit_s": round(fit_s, 1),
            "artifact_mb": round((model_dir / MODEL_FILE).stat().st_size / 1e6, 2),
        },
    }
    m["latency"] = {"load_s": round(load_s, 2), **_latency(model, list(val["text"]), latency_n)}
    m["run"] = run_info(
        split="val", rows=len(val), split_content_sha256=manifest["splits"]["val"]["content_sha256"]
    )

    card["val_metrics"] = {
        "macro_f1": m["val"]["overall"]["macro_f1"],
        "accuracy": m["val"]["overall"]["accuracy"],
        "macro_f1_real_only": m["val"]["origin_real"]["macro_f1"],
        "ece": m["calibration"]["ece"],
    }
    (model_dir / CARD_FILE).write_text(json.dumps(card, indent=2))

    out.mkdir(parents=True, exist_ok=True)
    plot_confusion(
        cm,
        labels,
        out / "confusion_matrix.png",
        f"Fast tier, val (n={len(res)}): macro-F1 {m['val']['overall']['macro_f1']:.3f}",
    )
    plot_reliability(m["calibration"], out / "reliability.png", "Fast tier (calibrated), val")
    (out / "metrics.json").write_text(json.dumps(m, indent=2, default=str))
    (out / "report.md").write_text(report_markdown(m))
    return m


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--model-dir", default=None, help="default: $MODELS_DIR/fast_tier")
    ap.add_argument("--out", default=None, help="default: results/fast_tier[_aug]")
    ap.add_argument(
        "--style-aug", action="store_true", help="ablation: also train on train_style_aug"
    )
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    suffix = "_aug" if args.style_aug else ""
    model_dir = args.model_dir or get_settings().models_dir / f"fast_tier{suffix}"
    out = Path(args.out) if args.out else RESULTS.parent / f"fast_tier{suffix}"
    m = train(model_dir, out, style_aug=args.style_aug)
    v = m["val"]
    print(
        json.dumps(
            {
                k: {"macro_f1": v[k].get("macro_f1"), "accuracy": v[k].get("accuracy")}
                for k in ("overall", "origin_real", "without_meeting_scheduling")
            },
            indent=1,
        )
    )
    print(f"version {m['card']['version']}, ECE {m['calibration']['ece']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
