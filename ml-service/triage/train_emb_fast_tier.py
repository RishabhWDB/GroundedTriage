"""Train the embedding fast tier (P3.13) on train (optionally + train_style_aug),
select C on val, and compare with the TF-IDF fast tier.

    python -m triage.train_emb_fast_tier [--style-aug]   # == make fast-tier-emb[-aug]

Embeddings are cached (datasets/raw/emb_cache/), so re-runs only fit the LR.
Writes models/fast_tier_emb[_aug]/ and results/fast_tier_emb[_aug]/
{metrics.json, report.md, confusion_matrix.png}. Reports memory (peak RSS,
swap) and latency (embedder load, single-ticket and batched encode + LR,
uncached). The test split is never read.
"""

from __future__ import annotations

import argparse
import json
import logging
import time
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

from app.settings import REPO_ROOT, get_settings
from app.taxonomy import topic_categories
from data.build import OUT_DIR
from eval.classification import (
    calibration,
    classification_metrics,
    confusion,
    coverage_curve,
    latency_summary,
    plot_confusion,
    sliced_metrics,
)
from eval.runinfo import run_info
from triage.emb_fast_tier import EmbFastTier
from triage.embedder import Embedder, EmbeddingCache
from triage.fast_tier import CARD_FILE, MODEL_FILE

logger = logging.getLogger(__name__)

RESULTS = REPO_ROOT / "results"
C_GRID = (0.25, 1.0, 4.0, 16.0, 64.0)
TAUS = (0.4, 0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.95)
SEED = 42


def fit_lr(x, y, c: float):
    from sklearn.linear_model import LogisticRegression

    return LogisticRegression(C=c, class_weight="balanced", max_iter=3000).fit(x, y)


def select_c(x_tr, y_tr, x_val, y_val, grid=C_GRID):
    rows, best = [], None
    for c in grid:
        t0 = time.perf_counter()
        lr = fit_lr(x_tr, y_tr, c)
        m = classification_metrics(y_val, lr.predict(x_val), topic_categories())
        row = {
            "C": c,
            "val_macro_f1": m["macro_f1"],
            "val_accuracy": m["accuracy"],
            "fit_s": round(time.perf_counter() - t0, 1),
        }
        logger.info("C=%s val macro-F1 %.4f", c, row["val_macro_f1"])
        rows.append(row)
        if best is None or row["val_macro_f1"] > best[0]["val_macro_f1"]:
            best = (row, lr)
    return best[0]["C"], best[1], rows


def latency(tier: EmbFastTier, texts: list[str], n: int = 100) -> dict:
    """Uncached: embed + LR, one ticket at a time and as one batch."""
    rng = np.random.default_rng(SEED)
    sample = [texts[i] for i in rng.choice(len(texts), size=min(n, len(texts)), replace=False)]
    tier.predict(sample[:2])  # warm-up (loads the embedder if needed)
    single = []
    for t in sample:
        t0 = time.perf_counter()
        tier.predict([t])
        single.append((time.perf_counter() - t0) * 1000)
    t0 = time.perf_counter()
    tier.predict(sample)
    batch_s = time.perf_counter() - t0
    return {
        "single_ticket_ms": latency_summary(single),
        "batched": {
            "tickets": len(sample),
            "ms_per_ticket": round(batch_s * 1000 / len(sample), 2),
        },
    }


def tfidf_reference(style_aug: bool) -> dict | None:
    path = RESULTS / ("fast_tier_aug" if style_aug else "fast_tier") / "metrics.json"
    if not path.exists():
        return None
    m = json.loads(path.read_text())
    return {
        "version": m["card"]["version"],
        "macro_f1": m["val"]["overall"]["macro_f1"],
        "accuracy": m["val"]["overall"]["accuracy"],
        "macro_f1_real": m["val"]["origin_real"]["macro_f1"],
        "ece": m["calibration"]["ece"],
        "per_class_f1": {c: v["f1"] for c, v in m["val"]["overall"]["per_class"].items()},
        "single_ticket_p50_ms": m["latency"]["single_ticket_ms"]["p50_ms"],
        "artifact_mb": m["training"]["artifact_mb"],
    }


def report_markdown(m: dict) -> str:
    v, ref, card = m["val"]["overall"], m["tfidf_reference"], m["card"]
    lat = m["latency"]
    lines = [
        f"# Embedding fast tier ({card['embedding_model']} + LR) on val",
        "",
        f"Version `{card['version']}`; train"
        + (f" + train_style_aug ({card['style_aug_rows']} rows)" if card["style_aug"] else "")
        + f" ({card['train_rows']} rows); C={card['C']} by val macro-F1; uncalibrated. "
        "Generated by `make fast-tier-emb"
        + ("-aug" if card["style_aug"] else "")
        + "`. Test is not used. **No accept/reject decision** (deferred to Phase 7).",
        "",
        "| | embedding + LR | TF-IDF + LR (same train) |",
        "|---|---|---|",
        f"| val macro-F1 | {v['macro_f1']} | {ref['macro_f1'] if ref else '–'} |",
        f"| val accuracy | {v['accuracy']} | {ref['accuracy'] if ref else '–'} |",
        f"| val macro-F1, real only | {m['val']['origin_real']['macro_f1']} | "
        f"{ref['macro_f1_real'] if ref else '–'} |",
        f"| ECE | {m['calibration']['ece']} | {ref['ece'] if ref else '–'} |",
        *[
            f"| F1 {c} | {p['f1']} | {ref['per_class_f1'].get(c, '–') if ref else '–'} |"
            for c, p in v["per_class"].items()
        ],
        f"| single ticket p50 (ms) | {lat['single_ticket_ms']['p50_ms']} | "
        f"{ref['single_ticket_p50_ms'] if ref else '–'} |",
        f"| artifact | LR {m['training']['artifact_mb']} MB + {card['embedding_model']} "
        f"(~130 MB HF cache) | {ref['artifact_mb'] if ref else '–'} MB |",
        "",
        "## Memory and latency (this machine: M1, 8 GB)",
        "",
        f"- embedder load {lat.get('embedder_load_s')} s on `{lat.get('device')}`; single ticket "
        f"(embed + LR, uncached) p50 {lat['single_ticket_ms']['p50_ms']} ms, p95 "
        f"{lat['single_ticket_ms']['p95_ms']} ms; batched "
        f"{lat['batched']['ms_per_ticket']} ms/ticket",
        f"- embedding all texts (first run, before caching): {m['training']['embed_s']} s",
        f"- peak RSS {m['run']['peak_rss_mb']} MB; swap at end: {m['run']['swap_usage_at_end']}",
        "",
        "## C selection",
        "",
        "| C | val macro-F1 | val accuracy | fit s |",
        "|---|---|---|---|",
        *[
            f"| {r['C']} | {r['val_macro_f1']} | {r['val_accuracy']} | {r['fit_s']} |"
            for r in m["c_selection"]
        ],
        "",
        "## Confidence vs coverage",
        "",
        "| tau | share >= tau | accuracy |",
        "|---|---|---|",
        *[
            f"| {r['tau']} | {r['accepted_share']} | {r['accepted_accuracy']} |"
            for r in m["coverage"]
        ],
        "",
    ]
    return "\n".join(lines)


def train(
    style_aug: bool = False,
    data_dir: Path = OUT_DIR,
    model_dir: Path | None = None,
    out: Path | None = None,
    embedder: Embedder | None = None,
    grid=C_GRID,
    latency_n: int = 100,
) -> dict:
    import joblib
    import sklearn

    suffix = "_aug" if style_aug else ""
    model_dir = Path(model_dir or get_settings().models_dir / f"fast_tier_emb{suffix}")
    out = Path(out or RESULTS / f"fast_tier_emb{suffix}")
    tr = pd.read_parquet(data_dir / "train.parquet")
    aug_rows = 0
    if style_aug:
        aug = pd.read_parquet(data_dir / "train_style_aug.parquet")
        aug_rows = len(aug)
        tr = pd.concat([tr, aug.drop(columns=["aug_of"])], ignore_index=True)
    val = pd.read_parquet(data_dir / "val.parquet")
    manifest = json.loads((data_dir / "manifest.json").read_text())

    embedder = embedder or Embedder()
    cache = EmbeddingCache(embedder)
    t0 = time.perf_counter()
    x_tr, x_val = cache.encode(list(tr["text"])), cache.encode(list(val["text"]))
    embed_s = time.perf_counter() - t0
    best_c, lr, c_rows = select_c(x_tr, tr["category"], x_val, val["category"], grid)

    trained_at = datetime.now(UTC)
    train_sha = manifest["splits"]["train"]["content_sha256"]
    card = {
        "version": f"fast-emb-{trained_at:%Y%m%d%H%M%S}-{train_sha[:8]}",
        "task": "category",
        "model": f"{embedder.model_name} CLS embeddings + LR (balanced), uncalibrated",
        "embedding_model": embedder.model_name,
        "max_length": embedder.max_length,
        "trained_at": trained_at.isoformat(timespec="seconds"),
        "train_rows": len(tr),
        "style_aug": style_aug,
        "style_aug_rows": aug_rows,
        "C": best_c,
        "sklearn_version": sklearn.__version__,
        "classes": [str(c) for c in lr.classes_],
    }
    model_dir.mkdir(parents=True, exist_ok=True)
    joblib.dump(lr, model_dir / MODEL_FILE, compress=3)
    (model_dir / CARD_FILE).write_text(json.dumps(card, indent=2))
    tier = EmbFastTier.load(model_dir, embedder)
    if tier is None:
        raise RuntimeError(f"saved embedding fast tier in {model_dir} failed to load")

    preds = tier.predict(list(val["text"]), vectors=x_val)
    res = val[["id", "origin", "category", "text"]].rename(columns={"category": "gold"})
    res["pred"] = [p.category for p in preds]
    conf = np.array([p.confidence for p in preds])
    correct = (res["gold"] == res["pred"]).to_numpy()
    labels = topic_categories()
    cm = confusion(res["gold"], res["pred"], labels)
    m: dict = {
        "card": card,
        "val": sliced_metrics(res, labels=labels),
        "confusion_matrix": {"labels": labels, "matrix": cm},
        "calibration": calibration(conf, correct),
        "coverage": coverage_curve(conf, correct, TAUS),
        "c_selection": c_rows,
        "training": {
            "embed_s": round(embed_s, 1),
            "artifact_mb": round((model_dir / MODEL_FILE).stat().st_size / 1e6, 3),
        },
        "tfidf_reference": tfidf_reference(style_aug),
    }
    m["latency"] = latency(tier, list(val["text"]), latency_n)
    m["latency"]["embedder_load_s"] = (
        round(embedder.load_s, 2) if embedder.load_s is not None else None
    )
    m["latency"]["device"] = embedder.device
    m["run"] = run_info(split="val", rows=len(val))
    card["val_metrics"] = {
        "macro_f1": m["val"]["overall"]["macro_f1"],
        "accuracy": m["val"]["overall"]["accuracy"],
        "ece": m["calibration"]["ece"],
    }
    (model_dir / CARD_FILE).write_text(json.dumps(card, indent=2))
    out.mkdir(parents=True, exist_ok=True)
    plot_confusion(
        cm,
        labels,
        out / "confusion_matrix.png",
        f"Embedding fast tier, val: macro-F1 {m['val']['overall']['macro_f1']:.3f}",
    )
    (out / "metrics.json").write_text(json.dumps(m, indent=2, default=str))
    (out / "report.md").write_text(report_markdown(m))
    return m


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--style-aug", action="store_true")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    print(report_markdown(train(args.style_aug)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
