"""Retrieval evaluation (P5.2): recall@1/3/5 and MRR on the WixQA QA pairs.

    python -m eval.retrieval            # == make retrieval-eval

Document level: a question is a hit at k when any of its gold article_ids
is among the documents of the top-k chunks (chunks deduplicated to their
documents, in rank order; MRR uses the first gold document's rank). Scored
for the dense retriever and the hybrid (dense + full-text RRF) one, on the
200 expert-written and 200 simulated questions. Writes results/retrieval/.
"""

from __future__ import annotations

import argparse
import json
import logging
import time
from pathlib import Path

import numpy as np

from app.settings import REPO_ROOT, get_settings
from eval.classification import latency_summary
from eval.runinfo import run_info
from rag.kb import KB_MAX_LENGTH, connect, load_wixqa_qa
from rag.retriever import Retriever

logger = logging.getLogger(__name__)

RESULTS = REPO_ROOT / "results" / "retrieval"
KS = (1, 3, 5)
DEPTH = 10  # chunks fetched per question (more chunks -> more distinct documents)


def doc_ranking(doc_ids: list[str]) -> list[str]:
    seen, out = set(), []
    for d in doc_ids:
        if d not in seen:
            seen.add(d)
            out.append(d)
    return out


def score_question(ranked_docs: list[str], gold: set[str], ks=KS) -> dict:
    rank = next((i + 1 for i, d in enumerate(ranked_docs) if d in gold), None)
    return {**{f"recall@{k}": float(rank is not None and rank <= k) for k in ks},
            "rr": 1.0 / rank if rank else 0.0}  # fmt: skip


def aggregate(rows: list[dict], ks=KS) -> dict:
    if not rows:
        return {"n": 0}
    out = {"n": len(rows)}
    for k in ks:
        out[f"recall@{k}"] = round(float(np.mean([r[f"recall@{k}"] for r in rows])), 4)
    out["mrr"] = round(float(np.mean([r["rr"] for r in rows])), 4)
    return out


def evaluate(retriever: Retriever, kinds=("expertwritten", "simulated"), modes=("dense", "hybrid"),
             reranker=None):  # fmt: skip
    """modes: dense | hybrid | dense+rerank (the last needs `reranker`)."""
    m: dict = {"depth": DEPTH, "results": {}, "latency_ms": {}}
    for mode in modes:
        lat = []
        retriever.reranker = reranker if mode == "dense+rerank" else None
        for kind in kinds:
            rows = []
            for qa in load_wixqa_qa(kind):
                t0 = time.perf_counter()
                res = retriever.search(qa.question, k=DEPTH, hybrid=mode == "hybrid")
                lat.append((time.perf_counter() - t0) * 1000)
                ranked = doc_ranking([c.doc_id for c in res.chunks])
                rows.append(score_question(ranked, set(qa.article_ids)))
            m["results"][f"{mode}/{kind}"] = aggregate(rows)
            logger.info("%s/%s: %s", mode, kind, m["results"][f"{mode}/{kind}"])
        m["latency_ms"][mode] = latency_summary(lat)
    retriever.reranker = None
    return m


FLOOR_KEEP = 0.95  # the floor keeps at least this share of answerable questions
FLOOR_TICKETS = 400


def floor_analysis(retriever: Retriever, val_texts: list[str], k: int = 5) -> dict:
    """Retrieval-floor rule for the faithfulness gate: the highest floor that
    keeps >= FLOOR_KEEP of the answerable WixQA questions (best top-k score),
    and how many out-of-domain val tickets (Tobi-Bueck, generic IT support
    the Wix KB doesn't cover) it would send straight to abstention."""
    answerable = [
        retriever.search(qa.question, k=k).max_score
        for kind in ("expertwritten", "simulated")
        for qa in load_wixqa_qa(kind)
    ]
    tickets = [retriever.search(t, k=k).max_score for t in val_texts]
    floor = float(np.quantile(answerable, 1 - FLOOR_KEEP))
    q = (0.05, 0.25, 0.5, 0.75, 0.95)
    return {
        "rule": f"floor = {1 - FLOOR_KEEP:.0%} quantile of answerable WixQA questions' best score",
        "floor": round(floor, 4),
        "answerable_n": len(answerable),
        "answerable_kept": round(float(np.mean(np.array(answerable) >= floor)), 4),
        "val_tickets_n": len(tickets),
        "val_tickets_below_floor": round(float(np.mean(np.array(tickets) < floor)), 4),
        "answerable_quantiles": {str(x): round(float(np.quantile(answerable, x)), 4) for x in q},
        "val_ticket_quantiles": {str(x): round(float(np.quantile(tickets, x)), 4) for x in q},
    }


def report_markdown(m: dict) -> str:
    lines = [
        "# Retrieval on WixQA (document-level)",
        "",
        "Generated by `make retrieval-eval`. A hit at k: a gold article is among the documents of "
        f"the top chunks (top {m['depth']} chunks deduplicated to documents). KB: {m['kb']}.",
        "",
        "| retriever | questions | n | recall@1 | recall@3 | recall@5 | MRR |",
        "|---|---|---|---|---|---|---|",
    ]
    for key, r in m["results"].items():
        mode, kind = key.split("/")
        lines.append(f"| {mode} | {kind} | {r['n']} | {r['recall@1']} | {r['recall@3']} | "
                     f"{r['recall@5']} | {r['mrr']} |")  # fmt: skip
    lines += ["", "Query latency (embed + SQL from this Mac to Supabase Mumbai, ms):", ""]
    for mode, lat in m["latency_ms"].items():
        lines.append(f"- {mode}: p50 {lat['p50_ms']}, p95 {lat['p95_ms']}, max {lat['max_ms']}")
    if "reranker" in m:
        rr = m["reranker"]
        lines += [
            "",
            f"Reranker `{rr['model']}` on {rr['device']}: dense top-{rr['candidates']} reranked; "
            f"load {rr['load_s']} s (peak RSS of the whole run below).",
        ]
    if "floor" in m:
        f = m["floor"]
        lines += [
            "",
            "## Retrieval floor for the faithfulness gate",
            "",
            f"Rule: {f['rule']} -> **floor {f['floor']}** (keeps {f['answerable_kept']:.1%} of "
            f"{f['answerable_n']} answerable questions). Out-of-domain val tickets (Tobi-Bueck, "
            f"n={f['val_tickets_n']}) below it: **{f['val_tickets_below_floor']:.1%}**.",
            "",
            f"Best-score quantiles, answerable questions: {f['answerable_quantiles']}; "
            f"val tickets: {f['val_ticket_quantiles']}.",
        ]
    lines += [
        "",
        f"Peak RSS {m['run']['peak_rss_mb']} MB; swap: {m['run']['swap_usage_at_end']}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    from rag.kb import storage
    from triage.embedder import Embedder

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(RESULTS))
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    conn = connect(get_settings().database_url or None)
    emb = Embedder(max_length=KB_MAX_LENGTH)
    retriever = Retriever(conn, emb.encode)
    from rag.reranker import CrossEncoderReranker

    reranker = CrossEncoderReranker()
    m = evaluate(retriever, modes=("dense", "hybrid", "dense+rerank"), reranker=reranker)
    m["reranker"] = {
        "model": reranker.model_name,
        "candidates": retriever.rerank_candidates,
        "device": reranker.device,
        "load_s": round(reranker.load_s or 0, 2),
    }
    import pandas as pd

    from data.build import OUT_DIR

    val = pd.read_parquet(OUT_DIR / "val.parquet").sample(n=FLOOR_TICKETS, random_state=42)
    m["floor"] = floor_analysis(retriever, list(val["text"]))
    st = storage(conn)
    m["kb"] = f"{st['documents']} documents, {st['chunks']} chunks"
    m["run"] = run_info()
    conn.close()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "metrics.json").write_text(json.dumps(m, indent=2, default=str))
    (out / "report.md").write_text(report_markdown(m))
    print(report_markdown(m))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
