"""Write config/monitoring.yaml (P7.3): the category reference distribution
for the PSI drift check, plus the alert settings.

    python -m eval.monitoring_ref      # == make monitoring-ref

The reference is the val split's category shares, Spam included: the rows of
`spam_val.parquet` that carry a category (its SpamAssassin ham rows have
none), i.e. topic val + spam val. `train` itself is capped (Technical Issue
cut to 5x Spam), so its shares are not the data's natural ones; val is
stratified from the same group-aware pool and keeps them.
"""

from __future__ import annotations

import json

import pandas as pd

from app.settings import REPO_ROOT
from app.taxonomy import categories
from data.build import OUT_DIR

PATH = REPO_ROOT / "config" / "monitoring.yaml"
PSI_ALERT = 0.2
MIN_TICKETS = 30

HEADER = """\
# Monitoring (P7.3), read by internal/monitoring. Generated by
# `make monitoring-ref` from datasets/processed/spam_val.parquet; edit the
# settings below by hand, re-generate the reference only after a data rebuild.
#
# category_psi = sum_c (p_c - q_c) * ln(p_c / q_c) over the day's latest
# classification per ticket (p) vs this reference (q); shares are floored at
# 1e-4. PSI > psi_alert is flagged on the dashboard (rule of thumb: < 0.1
# stable, 0.1-0.2 moderate shift, > 0.2 significant). Days with fewer than
# min_tickets classified tickets get no PSI (too noisy).
"""


def main() -> int:
    val = pd.read_parquet(OUT_DIR / "spam_val.parquet")
    val = val[val["category"].notna()]
    counts = val["category"].value_counts()
    ref = {c: round(float(counts.get(c, 0)) / len(val), 6) for c in categories()}
    lines = [
        HEADER,
        "version: 1",
        f"psi_alert: {PSI_ALERT}",
        f"min_tickets: {MIN_TICKETS}",
        f"reference_source: val split ({len(val)} rows)",
        "reference:",
    ]
    lines += [f"  {json.dumps(c)}: {v}" for c, v in ref.items()]
    PATH.write_text("\n".join(lines) + "\n")
    print(PATH.read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
