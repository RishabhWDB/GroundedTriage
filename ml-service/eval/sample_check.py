"""Out-of-domain sanity check on the 22 hand-written sample emails (P3.5a).

    python -m eval.sample_check [--with-baseline]     # == make sample-check

The splits put each real class in one source (Tobi-Bueck LLM-written tickets
vs SpamAssassin human-written spam), so val/test cannot show whether a model
learned topic or source style. datasets/sample_emails.csv is hand-written
and labelled, in neither source. 22 rows is a sanity check, not a metric:
it is reported as counts, never as a headline number.

Writes results/ood/{sample_emails.md, sample_emails.json}: per-row
predictions from the cascade (fast tier, plus deep tier if present), the
SCRIBE baseline with --with-baseline (loads BART-MNLI in this process,
~1.6 GB), and the fast tier's strongest Spam features.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd

from app.interfaces import TicketText
from app.settings import REPO_ROOT, get_settings
from app.textinput import model_input
from eval.runinfo import run_info
from triage.cascade import Cascade, load_tau
from triage.deep_tier import DeepTier
from triage.fast_tier import FastTier
from triage.urgency import UrgencyPredictor

logger = logging.getLogger(__name__)

SAMPLE = REPO_ROOT / "datasets" / "sample_emails.csv"
RESULTS = REPO_ROOT / "results" / "ood"


def load_sample(path: Path = SAMPLE) -> pd.DataFrame:
    df = pd.read_csv(path, dtype=str).fillna("")
    df = df.rename(columns=str.lower)
    df["id"] = [f"sample-{i:02d}" for i in range(len(df))]
    df["text"] = [model_input(s, b) for s, b in zip(df["subject"], df["body"], strict=True)]
    return df


def top_features(fast: FastTier, category: str, n: int = 20) -> list[str]:
    """Largest LR coefficients for one class (the calibrated model's base pipeline)."""
    est = fast.model.calibrated_classifiers_[0].estimator
    names = est.named_steps["features"].get_feature_names_out()
    lr = est.named_steps["lr"]
    if category not in list(lr.classes_):
        return []  # e.g. Spam, which the 5-class topic model no longer predicts
    coef = lr.coef_[list(lr.classes_).index(category)]
    return [str(names[j]) for j in np.argsort(coef)[-n:][::-1]]


def run(fast: FastTier, deep, df: pd.DataFrame, with_baseline: bool = False) -> dict:
    cascade = Cascade(fast, deep, UrgencyPredictor(None), load_tau())
    res = cascade.run(list(df["text"]))
    rows = []
    for (_, r), c in zip(df.iterrows(), res, strict=True):
        rows.append(
            {
                "id": r["id"],
                "subject": r["subject"],
                "gold": r["label"],
                "fast": c.fast.category,
                "fast_confidence": round(c.fast.confidence, 3),
                "cascade": c.category,
                "tier": c.tier,
            }
        )
    systems = ["fast", "cascade"]
    if with_baseline:
        from baseline.scribe import ScribeClassifier

        tickets = [
            TicketText(id=r["id"], subject=r["subject"], body=r["body"]) for _, r in df.iterrows()
        ]
        for row, p in zip(rows, ScribeClassifier().classify(tickets), strict=True):
            row["scribe"] = p.category
        systems.append("scribe")
    out = {
        "rows": rows,
        "correct": {s: sum(r[s] == r["gold"] for r in rows) for s in systems},
        "predicted_spam": {s: sum(r[s] == "Spam" for r in rows) for s in systems},
        "gold_spam": sum(r["gold"] == "Spam" for r in rows),
        "n": len(rows),
        "models": cascade.model_versions(),
        "fast_top_spam_features": top_features(fast, "Spam"),
        "run": run_info(),
    }
    return out


def report_markdown(m: dict) -> str:
    systems = list(m["correct"])
    lines = [
        "# Out-of-domain check: 22 hand-written sample emails",
        "",
        "`datasets/sample_emails.csv` is hand-written and in neither training source. "
        "A sanity check, not a metric (n=22). Generated by `make sample-check`.",
        f"Models: {m['models']}.",
        "",
        f"| system | correct | predicted Spam (gold Spam = {m['gold_spam']}) |",
        "|---|---|---|",
        *[f"| {s} | {m['correct'][s]}/{m['n']} | {m['predicted_spam'][s]} |" for s in systems],
        "",
        "| subject | gold | " + " | ".join(systems) + " | fast conf |",
        "|---|---|" + "---|" * len(systems) + "---|",
    ]
    for r in m["rows"]:
        cells = [r["subject"][:45].replace("|", "/"), r["gold"], *[r[s] for s in systems]]
        lines.append("| " + " | ".join(cells) + f" | {r['fast_confidence']} |")
    lines += [
        "",
        "Fast tier's strongest Spam features: "
        + ", ".join(f"`{f}`" for f in m["fast_top_spam_features"]),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--with-baseline", action="store_true", help="also run SCRIBE (loads BART-MNLI)"
    )
    ap.add_argument("--out", default=str(RESULTS))
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    s = get_settings()
    fast = FastTier.load(s.models_dir / "fast_tier")
    if fast is None:
        print("needs models/fast_tier/: run `make fast-tier` first")
        return 1
    m = run(fast, DeepTier(s.models_dir / "deep_tier"), load_sample(), args.with_baseline)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "sample_emails.json").write_text(json.dumps(m, indent=2, default=str))
    (out / "sample_emails.md").write_text(report_markdown(m))
    print(report_markdown(m))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
